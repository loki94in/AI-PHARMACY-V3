/**
 * LicenseService — machine fingerprint, local license caching, online validation.
 *
 * TESTING_MODE (default: true):
 *   - Skips all online validation
 *   - App runs freely for 1 year from first boot
 *   - Set testing_mode = 0 in app_license table to enforce real licensing
 */

import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { networkInterfaces } from 'os';
import axios from 'axios';
import { dbManager } from '../database/connection.js';
import { eventService } from './eventService.js';
import { activityTracker } from '../utils/activityTracker.js';

// Vercel license server URL — update after deploying
const LICENSE_SERVER = process.env.LICENSE_SERVER_URL || 'https://website-woad-seven-26.vercel.app';

let defaultAppVersion = '0.1.200';
try {
  const pkgJsonPath = path.join(process.cwd(), 'package.json');
  if (fs.existsSync(pkgJsonPath)) {
    const pkgJson = JSON.parse(fs.readFileSync(pkgJsonPath, 'utf8'));
    if (pkgJson?.version) defaultAppVersion = pkgJson.version;
  }
} catch (_) { }

export const APP_VERSION = process.env.APP_VERSION || defaultAppVersion;

// 1-year free testing window (ms)
const TESTING_FREE_PERIOD_MS = 365 * 24 * 60 * 60 * 1000;

export interface LicenseStatus {
  valid: boolean;
  mode: 'testing' | 'licensed' | 'grace' | 'expired' | 'revoked' | 'unlicensed' | 'mismatch';
  pharmacyName: string | null;
  licenseId: string | null;
  daysUntilExpiry: number | null; // null = unlimited (testing)
  message: string;
}

// --- Machine fingerprint (Windows MachineGuid or SHA256 fallback) ---
export function getMachineId(): string {
  let winGuid = '';
  try {
    const out = execSync(
      'reg query "HKEY_LOCAL_MACHINE\\SOFTWARE\\Microsoft\\Cryptography" /v MachineGuid',
      { encoding: 'utf8', timeout: 3000 }
    );
    const m = out.match(/MachineGuid\s+REG_SZ\s+(.+)/);
    if (m) winGuid = m[1].trim().toLowerCase();
  } catch {
    // Non-Windows or registry unavailable
  }

  if (winGuid) {
    return winGuid;
  }

  const nets = networkInterfaces();
  let mac = '';
  for (const name of Object.keys(nets)) {
    for (const net of (nets[name] || [])) {
      if (!net.internal && net.mac !== '00:00:00:00:00:00') {
        mac = net.mac;
        break;
      }
    }
    if (mac) break;
  }

  return crypto
    .createHash('sha256')
    .update(mac || 'generic-machine')
    .digest('hex')
    .substring(0, 32);
}

// --- Core license check (called on every app boot & periodic heartbeat) ---
export async function checkLicense(): Promise<LicenseStatus> {
  const db = await dbManager.getConnection();

  // Ingest pre-activation configuration generated by Web / Stub Installer
  const preActivationPath = path.join(process.cwd(), 'data', 'pre_activation.json');
  if (fs.existsSync(preActivationPath)) {
    try {
      const raw = fs.readFileSync(preActivationPath, 'utf8');
      const pre = JSON.parse(raw);
      if (pre && pre.licenseId) {
        const now = new Date().toISOString();
        const currentMachine = getMachineId();
        await db.run(
          `UPDATE app_license SET
             license_id = ?,
             pharmacy_name = ?,
             machine_id = ?,
             activated_at = ?,
             status = 'licensed',
             testing_mode = 0
           WHERE id = 1`,
          [pre.licenseId, pre.pharmacyName || null, currentMachine, now]
        );
        fs.unlinkSync(preActivationPath);
        eventService.broadcast('license_changed', {
          status: 'licensed',
          licenseId: pre.licenseId,
          pharmacyName: pre.pharmacyName,
        });
      }
    } catch (err) {
      console.warn('[licenseService] Error ingesting pre_activation.json:', err);
    }
  }

  const row = await db.get<any>('SELECT * FROM app_license WHERE id = 1');

  // Handle unactivated machine or fresh installation
  if (!row || !row.license_id) {
    if (row && row.testing_mode === 1) {
      const now = new Date().toISOString();
      const firstBoot = row?.activated_at ? new Date(row.activated_at).getTime() : Date.now();

      if (!row.activated_at) {
        await db.run(
          'UPDATE app_license SET activated_at = ?, status = ? WHERE id = 1',
          [now, 'testing']
        );
      }
      const elapsed = Date.now() - firstBoot;
      const remaining = Math.max(0, TESTING_FREE_PERIOD_MS - elapsed);
      const daysLeft = Math.floor(remaining / (24 * 60 * 60 * 1000));
      return {
        valid: daysLeft > 0,
        mode: 'testing',
        pharmacyName: null,
        licenseId: null,
        daysUntilExpiry: daysLeft,
        message: daysLeft > 30
          ? `Testing mode — ${daysLeft} days remaining`
          : daysLeft > 0
            ? `⚠️ Testing period expires in ${daysLeft} days. Please activate your license.`
            : 'Testing period expired. Please activate your license.',
      };
    }

    // Unactivated / fresh machine: strictly require an authorized license
    return {
      valid: false,
      mode: 'unlicensed',
      pharmacyName: null,
      licenseId: null,
      daysUntilExpiry: 0,
      message: 'AI Pharmacy OS is not activated on this PC. Please enter your License ID and License Key to activate.',
    };
  }

  // LICENSED MODE: validate online with hardware fingerprint and current app version
  const machineId = getMachineId();

  // Try online validation first
  try {
    const resp = await axios.get(`${LICENSE_SERVER}/api/license/validate`, {
      params: {
        licenseId: row.license_id,
        machineId,
        appVersion: APP_VERSION,
      },
      timeout: 5000,
    });

    if (resp.data.valid) {
      const expiresAt = resp.data.expiresAt || null;
      await db.run(
        'UPDATE app_license SET last_validated_at = ?, status = ?, expires_at = ?, pharmacy_name = ? WHERE id = 1',
        [new Date().toISOString(), 'licensed', expiresAt, resp.data.pharmacyName || row.pharmacy_name]
      );
      const daysLeft = resp.data.daysUntilExpiry ?? null;
      return {
        valid: true,
        mode: 'licensed',
        pharmacyName: resp.data.pharmacyName,
        licenseId: row.license_id,
        daysUntilExpiry: daysLeft,
        message: daysLeft !== null && daysLeft <= 30
          ? `⚠️ License expires in ${daysLeft} day${daysLeft !== 1 ? 's' : ''}. Please renew.`
          : `Licensed to ${resp.data.pharmacyName}`,
      };
    }

    // Server responded 200 but license is NOT valid — inspect reason code
    const code: string = resp.data.code || '';

    if (code === 'EXPIRED') {
      await db.run(
        'UPDATE app_license SET status = ?, last_validated_at = ? WHERE id = 1',
        ['expired', new Date().toISOString()]
      );
      return {
        valid: false,
        mode: 'expired',
        pharmacyName: row.pharmacy_name,
        licenseId: row.license_id,
        daysUntilExpiry: 0,
        message: 'License has expired. Please renew your license.',
      };
    }

    // REVOKED / SUSPENDED by admin — HARD BLOCK immediately
    if (code === 'REVOKED' || code === 'SUSPENDED' || resp.data.revoked || resp.data.status === 'suspended' || resp.data.status === 'revoked') {
      await db.run(
        'UPDATE app_license SET status = ?, last_validated_at = ? WHERE id = 1',
        ['revoked', new Date().toISOString()]
      );
      return {
        valid: false,
        mode: 'revoked',
        pharmacyName: row.pharmacy_name,
        licenseId: row.license_id,
        daysUntilExpiry: 0,
        message: 'License has been suspended by the administrator. Contact support to restore access.',
      };
    }

    if (code === 'MACHINE_MISMATCH') {
      await db.run(
        'UPDATE app_license SET status = ?, last_validated_at = ? WHERE id = 1',
        ['mismatch', new Date().toISOString()]
      );
      return {
        valid: false,
        mode: 'mismatch',
        pharmacyName: row.pharmacy_name,
        licenseId: row.license_id,
        daysUntilExpiry: 0,
        message: 'Hardware mismatch. This license is bound to another PC. Contact support to transfer.',
      };
    }
  } catch (err: any) {
    const respData = err.response?.data;
    const respCode = respData?.code || '';
    const status = err.response?.status;

    // Hard block on explicit 401/403 or known rejection codes
    if (status === 401 || status === 403 || respCode === 'EXPIRED' || respCode === 'REVOKED' || respCode === 'SUSPENDED' || respCode === 'MACHINE_MISMATCH') {
      const mode = respCode === 'EXPIRED' ? 'expired' : respCode === 'MACHINE_MISMATCH' ? 'mismatch' : 'revoked';
      await db.run(
        'UPDATE app_license SET status = ?, last_validated_at = ? WHERE id = 1',
        [mode, new Date().toISOString()]
      );
      return {
        valid: false,
        mode: mode as any,
        pharmacyName: row.pharmacy_name,
        licenseId: row.license_id,
        daysUntilExpiry: 0,
        message: respData?.error || 'License verification failed. Access is suspended.',
      };
    }
    // Network error / offline — fall through to local expires_at check
  }

  // ── OFFLINE FALLBACK ────────────────────────────────────────────────────────
  // Bug fix: use locally cached expires_at so the app runs for the FULL remaining
  // license period without internet — not just 7 days.
  if (row.expires_at) {
    const daysLeft = Math.floor((new Date(row.expires_at).getTime() - Date.now()) / 86400000);
    if (daysLeft > 0) {
      return {
        valid: true,
        mode: 'grace',
        pharmacyName: row.pharmacy_name,
        licenseId: row.license_id,
        daysUntilExpiry: daysLeft,
        message: `Offline — license valid for ${daysLeft} more day${daysLeft !== 1 ? 's' : ''}. Connect to internet to verify.`,
      };
    }
    return {
      valid: false,
      mode: 'expired',
      pharmacyName: row.pharmacy_name,
      licenseId: row.license_id,
      daysUntilExpiry: 0,
      message: 'License has expired. Please renew your license.',
    };
  }

  // Legacy fallback: no expires_at cached yet (row from before this fix) — use 7-day grace
  const lastValidated = row.last_validated_at ? new Date(row.last_validated_at).getTime() : 0;
  const graceDays = row.offline_grace_days ?? 7;
  const remaining = Math.max(0, (graceDays * 86400000) - (Date.now() - lastValidated));
  const daysLeft = Math.floor(remaining / 86400000);

  if (remaining > 0) {
    return {
      valid: true,
      mode: 'grace',
      pharmacyName: row.pharmacy_name,
      licenseId: row.license_id,
      daysUntilExpiry: daysLeft,
      message: `Offline mode — license unverified. ${daysLeft} day${daysLeft !== 1 ? 's' : ''} remaining before lockout.`,
    };
  }

  return {
    valid: false,
    mode: 'expired',
    pharmacyName: row.pharmacy_name,
    licenseId: row.license_id,
    daysUntilExpiry: 0,
    message: 'License validation failed. Please connect to the internet to verify your license.',
  };
}

// --- Activate license on this PC (called from stub installer / settings) ---
export async function activateLicense(licenseId: string, licenseKey: string): Promise<{
  success: boolean;
  pharmacyName?: string;
  error?: string;
}> {
  const machineId = getMachineId();
  const machineName = (() => {
    try { return execSync('hostname', { encoding: 'utf8', timeout: 2000 }).trim(); } catch { return 'Unknown PC'; }
  })();

  try {
    const resp = await axios.post(`${LICENSE_SERVER}/api/license/activate`, {
      licenseId,
      licenseKey,
      machineId,
      machineName,
    }, { timeout: 10000 });

    if (resp.data.success) {
      const db = await dbManager.getConnection();
      await db.run(`
        UPDATE app_license
        SET license_id = ?, machine_id = ?, pharmacy_name = ?,
            activated_at = ?, last_validated_at = ?, status = ?, testing_mode = 0
        WHERE id = 1
      `, [
        licenseId,
        machineId,
        resp.data.pharmacyName,
        resp.data.activatedAt || new Date().toISOString(),
        new Date().toISOString(),
        'licensed',
      ]);

      eventService.broadcast('license_changed', {
        status: 'licensed',
        licenseId,
        pharmacyName: resp.data.pharmacyName,
      });

      return { success: true, pharmacyName: resp.data.pharmacyName };
    }

    return { success: false, error: 'Activation failed' };
  } catch (err: any) {
    const msg = err.response?.data?.error || err.message || 'Network error';
    return { success: false, error: msg };
  }
}

// --- Check for app updates ---
export async function checkForUpdate(): Promise<{
  hasUpdate: boolean;
  currentVersion: string;
  latestVersion: string;
  downloadUrl?: string;
  updatePackageUrl?: string;
  packageSizeBytes?: number | null;
  installerSizeBytes?: number | null;
  totalBytes?: number | null;
  sha256?: string;
  changelog?: string;
} | null> {
  try {
    const db = await dbManager.getConnection();
    // Always use the running binary version as the ground truth version sent to the update server
    const currentVersion = APP_VERSION;

    const licRow = await db.get<any>('SELECT license_id FROM app_license WHERE id = 1');
    const machineId = getMachineId();

    const resp = await axios.get(`${LICENSE_SERVER}/api/updates/check`, {
      params: {
        version: currentVersion,
        licenseId: licRow?.license_id || undefined,
        machineId,
      },
      timeout: 8000,
    });

    const latestVersion = resp.data.latestVersion || currentVersion;
    const now = new Date().toISOString();
    await db.run(
      'UPDATE update_checks SET last_checked_at = ?, last_known_version = ?, current_version = ? WHERE id = 1',
      [now, latestVersion, currentVersion]
    );

    const rawTotalBytes = typeof resp.data.totalBytes === 'number'
      ? resp.data.totalBytes
      : (typeof resp.data.packageSizeBytes === 'number' ? resp.data.packageSizeBytes : null);

    return {
      hasUpdate: !!resp.data.hasUpdate,
      currentVersion,
      latestVersion,
      downloadUrl: resp.data.downloadUrl,
      updatePackageUrl: resp.data.updatePackageUrl,
      packageSizeBytes: resp.data.packageSizeBytes ?? null,
      installerSizeBytes: resp.data.installerSizeBytes ?? null,
      totalBytes: rawTotalBytes,
      sha256: resp.data.sha256,
      changelog: resp.data.changelog,
    };
  } catch {
    return null; // Offline or server error — silently ignore
  }
}

/** Report anonymous, technical crash/error telemetry (strictly zero business/patient data) */
export async function reportCrashTelemetry(errorData: {
  errorType: string;
  message: string;
  stack?: string;
}): Promise<void> {
  try {
    const db = await dbManager.getConnection();
    const licRow = await db.get<any>('SELECT license_id FROM app_license WHERE id = 1');
    const machineId = getMachineId();
    await axios.post(`${LICENSE_SERVER}/api/telemetry/report`, {
      machineId,
      licenseId: licRow?.license_id || null,
      appVersion: APP_VERSION,
      errorType: errorData.errorType,
      message: errorData.message,
      stack: errorData.stack,
    }, { timeout: 4000 });
  } catch {
    // Non-blocking telemetry
  }
}

// --- Self-Service License Renewal (customer enters 1-Year renewal key in Settings) ---
export async function renewLicenseSelf(renewalKey: string): Promise<{
  success: boolean;
  message?: string;
  expiresAt?: string;
  daysUntilExpiry?: number;
  error?: string;
}> {
  const db = await dbManager.getConnection();
  const row = await db.get<any>('SELECT * FROM app_license WHERE id = 1');
  if (!row?.license_id) {
    return { success: false, error: 'No active license found to renew. Please activate your license first.' };
  }

  const machineId = getMachineId();
  try {
    const resp = await axios.post(`${LICENSE_SERVER}/api/license/renew-self`, {
      licenseId: row.license_id,
      renewalKey: renewalKey.trim(),
      machineId,
    }, { timeout: 10000 });

    if (resp.data.success) {
      await db.run(
        'UPDATE app_license SET expires_at = ?, status = ?, last_validated_at = ? WHERE id = 1',
        [resp.data.expiresAt, 'licensed', new Date().toISOString()]
      );
      return {
        success: true,
        message: resp.data.message || 'License renewed successfully for 1 year.',
        expiresAt: resp.data.expiresAt,
        daysUntilExpiry: resp.data.daysUntilExpiry,
      };
    }
    return { success: false, error: resp.data.error || 'Renewal failed' };
  } catch (err: any) {
    return { success: false, error: err.response?.data?.error || err.message || 'Could not connect to renewal server' };
  }
}

// --- Background License Heartbeat (verifies active status every 60 minutes) ---
let licenseHeartbeatTimer: NodeJS.Timeout | null = null;
let lastKnownValidState: boolean = true;

export function initLicenseHeartbeat(): void {
  if (licenseHeartbeatTimer) return;
  // Heartbeat runs every 60 minutes (gated on activityTracker so idle machines do not poll)
  licenseHeartbeatTimer = setInterval(async () => {
    try {
      if (activityTracker.isIdle()) return;
      const status = await checkLicense();
      if (lastKnownValidState !== status.valid) {
        lastKnownValidState = status.valid;
        // Broadcast SSE event so client immediately reacts to remote suspend / activation
        eventService.broadcast('license_changed', {
          valid: status.valid,
          mode: status.mode,
          message: status.message,
        });
      }
    } catch (_) {}
  }, 60 * 60 * 1000);

  if (licenseHeartbeatTimer.unref) {
    licenseHeartbeatTimer.unref();
  }
}


